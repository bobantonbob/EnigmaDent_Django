def index(request):
    return render(request, 'departments/index.html', {'title': 'Послуги', 'page': 'departments'})


def _service(request, key):
    return render(request, 'departments/service_detail.html', {
        'title': SERVICES[key]['query'], 'page': key, 'service': SERVICES[key]
    })


def therapeutic(request):
    return _service(request, 'therapeutic')


def periodontology(request):
    return _service(request, 'periodontology')


def orthopedic(request):
    return _service(request, 'orthopedic')


def create(request):
    initial = {}
    if request.GET.get('service'):
        initial['about'] = request.GET['service']

    if request.method == 'POST':
        form = ArticlesForm(request.POST)
        if form.is_valid():
            appointment = form.save(commit=False)
            appointment.ip_address = get_client_ip(request)
            appointment.save()
            notify_telegram(
                '🦷 <b>Нова заявка Enigma Dent</b>\n'
                f'👤 {appointment.title}\n'
                f'📞 {appointment.phone}\n'
                f'✉️ {appointment.email or "не вказано"}\n'
                f'🩺 {appointment.about}\n'
                f'🕒 {appointment.preferred_time or "час не вказано"}\n'
                f'💬 {appointment.message or "без примітки"}\n'
                '✅ Заявку збережено в Django Admin'
            )
            messages.success(request, 'Заявку прийнято. Ми зв’яжемося з вами для підтвердження запису.')
            return redirect('create')
    else:
        form = ArticlesForm(initial=initial)

    return render(request, 'departments/create.html', {'title': 'Запис на прийом', 'page': 'appointment', 'form': form})


